  const params = new URLSearchParams(location.search);
  const qLang = (params.get('lang') || '').toLowerCase();
  const stored = (localStorage.getItem('castellum_lang') || '').toLowerCase();
  const nav = (navigator.language || 'ar').slice(0, 2).toLowerCase();
  let lang = LANGS.includes(qLang) ? qLang : LANGS.includes(stored) ? stored : LANGS.includes(nav) ? nav : 'ar';
  const d = DICT[lang];

  function t(key, vars) {
    let s = d[key] ?? DICT.ar[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    return s;
  }

  function applyStatic() {
    document.documentElement.lang = lang;
    document.documentElement.dir = d.dir;
    document.documentElement.dataset.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    document.querySelectorAll('[data-lang-switch] button').forEach((b) => {
      b.classList.toggle('is-on', b.dataset.lang === lang);
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });
  }

  function setLang(next) {
    if (!LANGS.includes(next) || next === lang) return;
    localStorage.setItem('castellum_lang', next);
    const url = new URL(location.href);
    url.searchParams.set('lang', next);
    location.href = url.toString();
  }

  document.querySelectorAll('[data-lang-switch] button').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });

  applyStatic();

  window.CLX = { lang, dir: d.dir, t, setLang, applyStatic, LANGS };
